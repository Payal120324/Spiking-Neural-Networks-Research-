class ReportGenerator:
    """
    Generates comprehensive research reports from experiment results.
    Supports HTML (primary), Markdown, and LaTeX output formats.
    """

    def __init__(self, config: dict):
        self.config = config
        rep_cfg = config.get("reporting", {})
        self.fmt = rep_cfg.get("format", "html")
        self.include_figures = rep_cfg.get("include_figures", True)
        self.include_tables = rep_cfg.get("include_tables", True)
        self.out_dir = Path(config.get("storage", {}).get("reports", "storage/results/reports"))
        self.out_dir.mkdir(parents=True, exist_ok=True)

    def generate(
        self,
        title: str,
        experiment_config: dict,
        classification_results: Optional[dict] = None,
        semantic_results: Optional[dict] = None,
        energy_results: Optional[dict] = None,
        domain_shift_results: Optional[dict] = None,
        dataset_stats: Optional[dict] = None,
        figure_paths: Optional[list[str]] = None,
        raw_results: Optional[dict] = None,
        filename: Optional[str] = None,
    ) -> str:
        """
        Generate a complete experiment report.

        Returns:
            path to the generated report file
        """
        timestamp = datetime.now().strftime("%Y-%m-%d %H:%M:%S")
        fname = filename or f"report_{datetime.now().strftime('%Y%m%d_%H%M%S')}"

        if self.fmt == "html":
            content = self._build_html(
                title, timestamp, experiment_config,
                classification_results, semantic_results, energy_results,
                domain_shift_results, dataset_stats, figure_paths, raw_results,
            )
            path = self.out_dir / f"{fname}.html"
            with open(path, "w", encoding="utf-8") as f:
                f.write(content)
        elif self.fmt == "markdown":
            content = self._build_markdown(
                title, timestamp, experiment_config,
                classification_results, semantic_results, energy_results,
                domain_shift_results, dataset_stats, raw_results,
            )
            path = self.out_dir / f"{fname}.md"
            with open(path, "w", encoding="utf-8") as f:
                f.write(content)
        elif self.fmt == "latex":
            content = self._build_latex(
                title, timestamp,
                classification_results, semantic_results, energy_results,
                domain_shift_results,
            )
            path = self.out_dir / f"{fname}.tex"
            with open(path, "w", encoding="utf-8") as f:
                f.write(content)
        else:
            raise ValueError(f"Unknown report format: {self.fmt}")

        # Always save raw JSON alongside
        json_path = self.out_dir / f"{fname}_raw.json"
        with open(json_path, "w") as f:
            json.dump(
                {
                    "title": title,
                    "timestamp": timestamp,
                    "classification": classification_results,
                    "semantic": semantic_results,
                    "energy": energy_results,
                    "domain_shift": domain_shift_results,
                },
                f, indent=2, default=str,
            )

        # Write results_summary.csv
        if energy_results:
            csv_path = self._write_results_summary_csv(
                energy_results, semantic_results, fname
            )
            logger.info(f"Results summary CSV -> {csv_path}")

        logger.info(f"Report generated -> {path}")
        logger.info(f"Raw JSON -> {json_path}")
        return str(path)

    def _write_results_summary_csv(self, energy_results: dict, semantic_results: dict, fname: str) -> str:
        """Write results_summary.csv with consolidated metrics."""
        import csv
        
        csv_path = self.out_dir / f"results_summary_{fname}.csv"
        
        with open(csv_path, "w", newline="", encoding="utf-8") as f:
            writer = csv.writer(f)
            
            # Header
            writer.writerow([
                "encoding", "accuracy_mean", "accuracy_std", 
                "f1_macro_mean", "f1_macro_std",
                "spike_sparsity_pct_mean", "spike_sparsity_pct_std",
                "energy_ratio_mean", "energy_ratio_std",
                "energy_savings_pct_mean", "energy_savings_pct_std",
                "semantic_preservation_score"
            ])
            
            # Rows
            for enc, er in energy_results.items():
                comp = er["comparison"]
                clf = er.get("classification", {})
                sem_score = semantic_results.get(enc, {}).get("mean_cosine_similarity", "")
                
                # Handle multi-seed vs single-seed results
                if "mean" in comp:
                    acc_mean = clf.get("accuracy", {}).get("mean", "")
                    acc_std = clf.get("accuracy", {}).get("std", "")
                    f1_mean = clf.get("f1_macro", {}).get("mean", "")
                    f1_std = clf.get("f1_macro", {}).get("std", "")
                    sparsity_mean = comp.get("spike_sparsity_pct", {}).get("mean", "")
                    sparsity_std = comp.get("spike_sparsity_pct", {}).get("std", "")
                    ratio_mean = comp["energy_ratio"]["mean"]
                    ratio_std = comp["energy_ratio"]["std"]
                    savings_mean = comp["energy_savings_pct"]["mean"]
                    savings_std = comp["energy_savings_pct"]["std"]
                else:
                    acc_mean = clf.get("accuracy", "")
                    acc_std = ""
                    f1_mean = clf.get("f1_macro", "")
                    f1_std = ""
                    sparsity_mean = comp.get("spike_sparsity_pct", "")
                    sparsity_std = ""
                    ratio_mean = comp.get("energy_ratio", "")
                    ratio_std = ""
                    savings_mean = comp.get("energy_savings_pct", "")
                    savings_std = ""
                
                writer.writerow([
                    enc,
                    acc_mean, acc_std,
                    f1_mean, f1_std,
                    sparsity_mean, sparsity_std,
                    ratio_mean, ratio_std,
                    savings_mean, savings_std,
                    sem_score
                ])
        
        return str(csv_path)

    # ─────────────────────────────────────────────────────────────────
    # HTML Builder
    # ─────────────────────────────────────────────────────────────────

    def _build_html(
        self, title, timestamp, config,
        clf_results, sem_results, energy_results, shift_results, ds_stats,
        figure_paths, raw_results,
    ) -> str:
        sections = []
        sections.append(f"<h1>{title}</h1>")
        sections.append(
            f'<div class="meta">'
            f"Generated: {timestamp} &bull; "
            f"Framework: Spike-Legal-NLP v1.0"
            f"</div>"
        )

        # TOC
        toc_items = []
        if ds_stats:
            toc_items.append('<li><a href="#dataset">Dataset Statistics</a></li>')
        if clf_results:
            toc_items.append('<li><a href="#classification">Classification Results</a></li>')
        if sem_results:
            toc_items.append('<li><a href="#semantic">Semantic Preservation</a></li>')
        if energy_results:
            toc_items.append('<li><a href="#energy">Energy Analysis</a></li>')
        if shift_results:
            toc_items.append('<li><a href="#domain">Domain Shift</a></li>')
        if figure_paths:
            toc_items.append('<li><a href="#figures">Figures</a></li>')
        toc_items.append('<li><a href="#hypotheses">Hypothesis Evaluation</a></li>')

        sections.append(
            f'<div class="toc"><h3>Contents</h3><ul>{"".join(toc_items)}</ul></div>'
        )

        # Abstract
        sections.append("<h2>Research Overview</h2>")
        sections.append(
            "<p>This report presents results from the <em>Spike Encoding for Legal Text "
            "Classification</em> research framework. The study compares transformer-based "
            "baselines (LegalBERT, BERT) with spiking neural networks (SNNs) using five "
            "spike encoding strategies, evaluated on legal NLP datasets from LexGLUE.</p>"
        )

        # Limitations and Caveats
        sections.append('<h2 id="limitations">Limitations and Caveats</h2>')
        sections.append('<div class="finding">')
        sections.append("<strong>Dataset Size:</strong> ")
        if ds_stats:
            for ds_name, stats in ds_stats.items():
                train_n = stats.get("splits", {}).get("train", {}).get("n_samples", "—")
                val_n = stats.get("splits", {}).get("validation", {}).get("n_samples", 
                        stats.get("splits", {}).get("test", {}).get("n_samples", "—"))
                test_n = stats.get("splits", {}).get("test", {}).get("n_samples", "—")
                sections.append(
                    f"{ds_name}: {train_n} train / {val_n} validation / {test_n} test samples. "
                )
        sections.append(
            "The small dataset size may limit statistical power and generalizability of results."
        )
        sections.append("<br><br>")
        sections.append(
            "<strong>Energy Model:</strong> Energy estimates are theoretical calculations based on "
            "the MAC (Multiply-Accumulate) and SOP (Synaptic Operation) energy models from "
            "Horowitz (2014) and Davies (2018). These are NOT measured on physical neuromorphic "
            "hardware. Actual energy consumption may vary significantly depending on hardware "
            "implementation, memory access patterns, and system-level factors."
        )
        sections.append("<br><br>")
        sections.append(
            "<strong>Stochastic Encodings:</strong> Poisson-based encodings are stochastic, "
            "so repeated runs produce different efficiency numbers. Multi-seed averaging is "
            "recommended for robust estimates."
        )
        sections.append("</div>")

        # Experiment config summary
        sections.append("<h3>Experiment Configuration</h3>")
        sections.append("<table><tr><th>Parameter</th><th>Value</th></tr>")
        enc_cfg = config.get("encoding", {})
        snn_cfg = config.get("snn", {})
        params = [
            ("Time Steps", enc_cfg.get("time_steps", "—")),
            ("SNN Hidden Size", snn_cfg.get("architecture", {}).get("hidden_size", "—")),
            ("SNN Epochs", snn_cfg.get("training", {}).get("num_epochs", "—")),
            ("SNN Beta (LIF)", snn_cfg.get("neuron", {}).get("beta", "—")),
            ("Max Sequence Length", config.get("preprocessing", {}).get("max_length", "—")),
        ]
        for k, v in params:
            sections.append(f"<tr><td>{k}</td><td><code>{v}</code></td></tr>")
        sections.append("</table>")

        # Dataset Statistics
        if ds_stats:
            sections.append('<h2 id="dataset">Dataset Statistics</h2>')
            for ds_name, stats in ds_stats.items():
                sections.append(f"<h3>{ds_name}</h3>")
                sections.append("<table><tr><th>Split</th><th>Samples</th>"
                               "<th>Classes</th><th>Avg Tokens</th><th>Max Tokens</th>"
                               "<th>>512 tokens</th></tr>")
                for split_name, sp in stats.get("splits", {}).items():
                    sections.append(
                        f"<tr><td>{split_name}</td>"
                        f"<td>{sp.get('n_samples', '—')}</td>"
                        f"<td>{sp.get('n_classes', '—')}</td>"
                        f"<td>{sp.get('token_stats', {}).get('mean', 0):.0f}</td>"
                        f"<td>{sp.get('token_stats', {}).get('max', 0)}</td>"
                        f"<td>{sp.get('token_stats', {}).get('pct_over_512', 0):.1%}</td>"
                        f"</tr>"
                    )
                sections.append("</table>")

        # Classification Results
        if clf_results:
            sections.append('<h2 id="classification">Classification Results</h2>')
            sections.append(
                '<div class="finding">These results compare transformer-based linear probes '
                "with SNN classifiers trained on spike-encoded embeddings.</div>"
            )
            sections.append(
                "<table><tr><th>Model / Encoding</th><th>Accuracy</th>"
                "<th>F1 Macro</th><th>F1 Micro</th></tr>"
            )
            for name, res in clf_results.items():
                if isinstance(res, dict):
                    acc = res.get("accuracy", res.get("final_val", {}).get("accuracy", "—"))
                    f1m = res.get("f1_macro", res.get("final_val", {}).get("f1_macro", "—"))
                    f1i = res.get("f1_micro", res.get("final_val", {}).get("f1_micro", "—"))
                    sections.append(
                        f"<tr><td><code>{name}</code></td>"
                        f"<td>{_fmt_pct(acc)}</td>"
                        f"<td>{_fmt_pct(f1m)}</td>"
                        f"<td>{_fmt_pct(f1i)}</td></tr>"
                    )
            sections.append("</table>")

        # Semantic Preservation
        if sem_results:
            sections.append('<h2 id="semantic">Semantic Preservation Analysis</h2>')
            sections.append(
                '<div class="finding">Measures how well spike encodings preserve the '
                "semantic geometry of the original transformer embeddings.</div>"
            )
            sections.append(
                "<table><tr><th>Encoding</th><th>Cosine Similarity</th>"
                "<th>Spearman ρ</th><th>Kendall τ</th><th>Top-10 NN</th></tr>"
            )
            for enc, res in sem_results.items():
                sections.append(
                    f"<tr><td><code>{enc}</code></td>"
                    f"<td>{_fmt_float(res.get('mean_cosine_similarity'))}</td>"
                    f"<td>{_fmt_float(res.get('spearman_rho'))}</td>"
                    f"<td>{_fmt_float(res.get('kendall_tau'))}</td>"
                    f"<td>{_fmt_pct(res.get('topk_nn_overlap_k10'))}</td></tr>"
                )
            sections.append("</table>")

        # Energy Analysis
        if energy_results:
            sections.append('<h2 id="energy">Energy Analysis</h2>')
            sections.append(
                '<div class="finding">Energy estimates based on Horowitz (2014): '
                "4.6 pJ/MAC (GPU), 0.9 pJ/SOP (neuromorphic), 100 pJ/DRAM-access.</div>"
            )
            # Summary cards
            sections.append('<div style="margin:20px 0">')
            for enc, er in energy_results.items():
                comp = er["comparison"]
                if "mean" in comp:
                    # Multi-seed results
                    ratio = comp["energy_ratio"]["mean"]
                    sections.append(
                        f'<div class="metric-card">'
                        f'<div class="metric-value">{ratio:.1f}×</div>'
                        f'<div class="metric-label">{enc.replace("_", " ")}<br>efficiency</div>'
                        f"</div>"
                    )
                else:
                    # Single-seed results
                    sections.append(
                        f'<div class="metric-card">'
                        f'<div class="metric-value">{comp["energy_ratio"]:.1f}×</div>'
                        f'<div class="metric-label">{enc.replace("_", " ")}<br>efficiency</div>'
                        f"</div>"
                    )
            sections.append("</div>")
            
            # Consolidated results table
            sections.append('<h3>Consolidated Results Summary</h3>')
            sections.append(
                "<table><tr><th>Encoding</th><th>Accuracy</th><th>F1 Macro</th>"
                "<th>Sparsity (%)</th><th>Energy Ratio</th><th>Energy Savings (%)</th>"
                "<th>Semantic Score</th></tr>"
            )
            for enc, er in energy_results.items():
                comp = er["comparison"]
                clf = er.get("classification", {})
                sem_score = sem_results.get(enc, {}).get("mean_cosine_similarity", "—")
                
                # Handle multi-seed vs single-seed results
                if "mean" in comp:
                    acc = f"{clf.get('accuracy', {}).get('mean', 0):.4f}±{clf.get('accuracy', {}).get('std', 0):.4f}"
                    f1 = f"{clf.get('f1_macro', {}).get('mean', 0):.4f}±{clf.get('f1_macro', {}).get('std', 0):.4f}"
                    sparsity = f"{comp.get('spike_sparsity_pct', {}).get('mean', 0):.1f}±{comp.get('spike_sparsity_pct', {}).get('std', 0):.1f}"
                    ratio = f"{comp['energy_ratio']['mean']:.1f}±{comp['energy_ratio']['std']:.1f}"
                    savings = f"{comp['energy_savings_pct']['mean']:.1f}±{comp['energy_savings_pct']['std']:.1f}"
                else:
                    acc = f"{clf.get('accuracy', 0):.4f}"
                    f1 = f"{clf.get('f1_macro', 0):.4f}"
                    sparsity = f"{comp.get('spike_sparsity_pct', 0):.1f}"
                    ratio = f"{comp['energy_ratio']:.1f}"
                    savings = f"{comp['energy_savings_pct']:.1f}"
                
                # Flag extreme ratios
                row_style = ""
                if isinstance(comp.get("energy_ratio"), dict):
                    ratio_val = comp["energy_ratio"]["mean"]
                    sparsity_val = comp.get("spike_sparsity_pct", {}).get("mean", 0)
                else:
                    ratio_val = comp.get("energy_ratio", 0)
                    sparsity_val = comp.get("spike_sparsity_pct", 0)
                
                if ratio_val > 50000 and sparsity_val > 95:
                    row_style = 'style="background-color: #fff3cd;"'
                    sections.append(
                        f"<tr {row_style}><td><code>{enc}</code> ⚠️</td>"
                        f"<td>{acc}</td><td>{f1}</td><td>{sparsity}</td>"
                        f"<td>{ratio}</td><td>{savings}</td><td>{f'{sem_score:.4f}' if isinstance(sem_score, float) else sem_score}</td></tr>"
                    )
                else:
                    sections.append(
                        f"<tr {row_style}><td><code>{enc}</code></td>"
                        f"<td>{acc}</td><td>{f1}</td><td>{sparsity}</td>"
                        f"<td>{ratio}</td><td>{savings}</td><td>{f'{sem_score:.4f}' if isinstance(sem_score, float) else sem_score}</td></tr>"
                    )
            sections.append("</table>")
            
            # Detailed energy breakdown
            sections.append('<h3>Detailed Energy Breakdown</h3>')
            sections.append(
                "<table><tr><th>Encoding</th><th>SNN Compute (µJ)</th>"
                "<th>SNN Memory (µJ)</th><th>SNN Total (µJ)</th>"
                "<th>vs Transformer</th></tr>"
            )
            for enc, er in energy_results.items():
                snn_e = er["snn_energy"]
                comp = er["comparison"]
                if "mean" in comp:
                    savings = f"{comp['energy_savings_pct']['mean']:.1f}±{comp['energy_savings_pct']['std']:.1f}%"
                else:
                    savings = f"−{comp['energy_savings_pct']:.1f}%"
                sections.append(
                    f"<tr><td><code>{enc}</code></td>"
                    f"<td>{snn_e['compute_energy_pj']/1e6:.4f}</td>"
                    f"<td>{snn_e['memory_energy_pj']/1e6:.4f}</td>"
                    f"<td>{snn_e['total_energy_pj']/1e6:.4f}</td>"
                    f"<td>{savings}</td></tr>"
                )
            # Transformer row
            first_er = list(energy_results.values())[0]
            t_e = first_er["transformer_energy"]
            sections.append(
                f"<tr style='font-weight:bold'><td>Transformer (baseline)</td>"
                f"<td>{t_e['compute_energy_pj']/1e6:.4f}</td>"
                f"<td>{t_e['memory_energy_pj']/1e6:.4f}</td>"
                f"<td>{t_e['total_energy_pj']/1e6:.4f}</td>"
                f"<td>—</td></tr>"
            )
            sections.append("</table>")

        # Domain Shift
        if shift_results:
            sections.append('<h2 id="domain">Domain Shift Evaluation</h2>')
            model_keys = [k for k in shift_results if not k.startswith("_")]
            ranking = shift_results.get("_ranking_by_robustness", model_keys)
            sections.append(
                f"<p>Models ranked by robustness (lowest accuracy drop): "
                f"<strong>{' &gt; '.join(ranking)}</strong></p>"
            )
            sections.append(
                "<table><tr><th>Model</th><th>Avg Accuracy Drop</th>"
                "<th>Avg Target Acc</th><th>Avg H-Score</th></tr>"
            )
            for model in model_keys:
                r = shift_results[model]
                sections.append(
                    f"<tr><td><code>{model}</code></td>"
                    f"<td>{r.get('avg_accuracy_drop', 0):.4f}</td>"
                    f"<td>{r.get('avg_target_accuracy', 0):.4f}</td>"
                    f"<td>{r.get('avg_h_score', 0):.4f}</td></tr>"
                )
            sections.append("</table>")

        # Figures
        if figure_paths and self.include_figures:
            sections.append('<h2 id="figures">Figures</h2>')
            for fig_path in figure_paths:
                if not fig_path or not os.path.exists(fig_path):
                    continue
                path = Path(fig_path)
                rel = os.path.relpath(fig_path, self.out_dir)
                caption = path.stem.replace("_", " ").title()
                if path.suffix.lower() in (".png", ".jpg", ".jpeg"):
                    sections.append(
                        f'<div class="figure">'
                        f'<img src="{rel}" alt="{caption}">'
                        f'<div class="figure-caption">Figure: {caption}</div>'
                        f"</div>"
                    )
                else:
                    sections.append(
                        f'<div class="figure">'
                        f'<p><a href="{rel}">[PDF Figure: {caption}]</a></p>'
                        f"</div>"
                    )

        # Hypothesis Evaluation
        sections.append('<h2 id="hypotheses">Hypothesis Evaluation</h2>')
        hypotheses = self._evaluate_hypotheses(clf_results, sem_results, energy_results, shift_results)
        for hyp_id, hyp_text, verdict, evidence in hypotheses:
            cls = "supported" if verdict == "✓ Supported" else "partial" if "Partial" in verdict else ""
            sections.append(
                f'<div class="hypothesis {cls}">'
                f"<strong>{hyp_id} — {verdict}</strong><br>"
                f"{hyp_text}<br>"
                f"<em>{evidence}</em>"
                f"</div>"
            )

        content = "\n".join(sections)
        return HTML_TEMPLATE.replace("{{ title }}", title).replace("{{ content }}", content).replace("{{ timestamp }}", timestamp)

    # ─────────────────────────────────────────────────────────────────
    # Hypothesis Evaluation
    # ─────────────────────────────────────────────────────────────────

    def _evaluate_hypotheses(self, clf, sem, energy, shift) -> list[tuple]:
        results = []

        # H1: Spike encoding achieves competitive classification performance
        if clf:
            snn_results = {k: v for k, v in clf.items() if "snn" in k.lower()}
            transformer_results = {k: v for k, v in clf.items() if "transformer" in k.lower() or "bert" in k.lower()}
            if snn_results and transformer_results:
                best_snn = max(
                    (v.get("accuracy", v.get("final_val", {}).get("accuracy", 0)) for v in snn_results.values()),
                    default=0,
                )
                best_transformer = max(
                    (v.get("accuracy", 0) for v in transformer_results.values()), default=1
                )
                gap = best_transformer - best_snn
                verdict = "✓ Supported" if gap < 0.15 else "⚠ Partial" if gap < 0.25 else "✗ Not Supported"
                results.append((
                    "H1", "Spike encoding achieves competitive classification performance.",
                    verdict, f"Best SNN acc={best_snn:.4f}, Best Transformer acc={best_transformer:.4f}, gap={gap:.4f}",
                ))

        # H2: Time-based encodings preserve legal semantics better than rate coding
        if sem:
            rate_cos = sem.get("poisson_rate", {}).get("mean_cosine_similarity", 0)
            temporal_encodings = ["latency", "temporal", "population"]
            temporal_scores = [sem.get(e, {}).get("mean_cosine_similarity", 0) for e in temporal_encodings]
            best_temporal = max(temporal_scores) if temporal_scores else 0
            verdict = "✓ Supported" if best_temporal > rate_cos else "⚠ Partial" if best_temporal >= rate_cos - 0.02 else "✗ Not Supported"
            results.append((
                "H2", "Time-based encodings preserve semantics better than rate coding.",
                verdict, f"Poisson rate cos={rate_cos:.4f}, best temporal cos={best_temporal:.4f}",
            ))

        # H3: Energy improvements shrink with memory access included
        if energy:
            first = list(energy.values())[0]
            compute_ratio = first["comparison"].get("compute_only_ratio", 0)
            total_ratio = first["comparison"].get("energy_ratio", 0)
            verdict = "✓ Supported" if compute_ratio > total_ratio else "⚠ Partial"
            results.append((
                "H3", "Energy improvements exist but shrink when memory access is included.",
                verdict, f"Compute-only ratio={compute_ratio:.1f}×, total ratio={total_ratio:.1f}×",
            ))

        # H4: Domain shift affects all models differently
        if shift:
            model_keys = [k for k in shift if not k.startswith("_")]
            if len(model_keys) >= 2:
                drops = [shift[m].get("avg_accuracy_drop", 0) for m in model_keys]
                variation = max(drops) - min(drops)
                verdict = "✓ Supported" if variation > 0.02 else "⚠ Partial"
                results.append((
                    "H4", "Domain shift affects all models differently.",
                    verdict, f"Accuracy drop range: {min(drops):.4f}–{max(drops):.4f} (variation={variation:.4f})",
                ))

        return results

