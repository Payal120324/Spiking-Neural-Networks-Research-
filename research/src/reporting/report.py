    # Markdown Builder
    # ─────────────────────────────────────────────────────────────────

    def _build_markdown(self, title, timestamp, config, clf, sem, energy, shift, ds_stats, raw) -> str:
        lines = [f"# {title}", f"", f"*Generated: {timestamp}*", ""]
        if clf:
            lines += ["## Classification Results", ""]
            lines += ["| Model | Accuracy | F1 Macro | F1 Micro |", "|-------|----------|----------|----------|"]
            for name, res in clf.items():
                if isinstance(res, dict):
                    acc = _fmt_pct(res.get("accuracy", res.get("final_val", {}).get("accuracy", "—")))
                    f1m = _fmt_pct(res.get("f1_macro", res.get("final_val", {}).get("f1_macro", "—")))
                    f1i = _fmt_pct(res.get("f1_micro", res.get("final_val", {}).get("f1_micro", "—")))
                    lines.append(f"| {name} | {acc} | {f1m} | {f1i} |")
            lines.append("")
        if sem:
            lines += ["## Semantic Preservation", ""]
            lines += ["| Encoding | Cosine | Spearman ρ | Kendall τ |", "|----------|--------|------------|-----------|"]
            for enc, res in sem.items():
                lines.append(
                    f"| {enc} | {_fmt_float(res.get('mean_cosine_similarity'))} "
                    f"| {_fmt_float(res.get('spearman_rho'))} "
                    f"| {_fmt_float(res.get('kendall_tau'))} |"
                )
            lines.append("")
        return "\n".join(lines)

    def _build_latex(self, title, timestamp, clf, sem, energy, shift) -> str:
        lines = [
            r"\documentclass[12pt]{article}",
            r"\usepackage{booktabs, amsmath, graphicx, hyperref}",
            r"\title{" + title.replace("_", r"\_") + "}",
            r"\date{" + timestamp + "}",
            r"\begin{document}\maketitle",
        ]
        if clf:
            lines += [
                r"\section{Classification Results}",
                r"\begin{table}[h]\centering",
                r"\begin{tabular}{lccc}\toprule",
                r"Model & Accuracy & F1 Macro & F1 Micro \\\midrule",
            ]
            for name, res in clf.items():
                if isinstance(res, dict):
                    acc = res.get("accuracy", res.get("final_val", {}).get("accuracy", 0))
                    f1m = res.get("f1_macro", res.get("final_val", {}).get("f1_macro", 0))
                    f1i = res.get("f1_micro", res.get("final_val", {}).get("f1_micro", 0))
                    safe_name = name.replace("_", r"\_")
                    lines.append(f"{safe_name} & {acc:.4f} & {f1m:.4f} & {f1i:.4f} \\\\")
            lines += [r"\bottomrule\end{tabular}", r"\caption{Classification Results}", r"\end{table}"]
        lines.append(r"\end{document}")
        return "\n".join(lines)


